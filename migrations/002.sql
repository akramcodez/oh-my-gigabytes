BEGIN IMMEDIATE;
CREATE TABLE IF NOT EXISTS catalog_releases(digest TEXT PRIMARY KEY,version INTEGER NOT NULL,payload TEXT NOT NULL,activated INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS catalog_state(singleton INTEGER PRIMARY KEY CHECK(singleton=1),active TEXT NOT NULL,previous TEXT,highest INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS ignores(id INTEGER PRIMARY KEY,rule TEXT NOT NULL,root BLOB NOT NULL,path BLOB NOT NULL,subtree INTEGER NOT NULL,created INTEGER NOT NULL,UNIQUE(rule,root,path,subtree));
PRAGMA user_version=2;
COMMIT;
